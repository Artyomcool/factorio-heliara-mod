#!/usr/bin/env python3
"""
Generate heliara/decal/weathered_siliceous_crust.lua from decals_layout.json.
Run whenever the atlas is regenerated.

Per-size params (min_sep, target) are read from the JSON 'sizes' section when
present (written by the GUI), falling back to SIZE_PARAMS for older files.
Collision-box dimensions are always derived from tile size.
"""

import json, pathlib
from collections import defaultdict

ROOT     = pathlib.Path(__file__).resolve().parents[3]
JSON_IN  = ROOT / 'art_sources/weathered_siliceous_crust/textures/decals_layout.json'
LUA_OUT  = ROOT / 'heliara/decal/weathered_siliceous_crust.lua'

data  = json.loads(JSON_IN.read_text())
ATLAS = '__heliara__/graphics/terrain/heliara_weathered_siliceous_crust_decals.png'

# Fallback params when JSON has no 'sizes' section (legacy files):
# (min_sep, probability)
SIZE_PARAMS_FALLBACK = {
    (8, 8): (14.0, 0.001),
    (4, 4): ( 7.0, 0.003),
    (2, 2): ( 3.5, 0.030),
    (2, 1): ( 2.0, 0.012),
    (1, 1): (None, 0.060),
}

json_sizes = data.get('sizes', {})   # may be absent in old files


def get_params(wt, ht):
    """Return (coll_hw, coll_hh, min_sep_or_None, probability)."""
    hw = round(wt * 0.5 - 0.1, 2)
    hh = round(ht * 0.5 - 0.1, 2)

    key_str = f'{wt}x{ht}'
    if key_str in json_sizes:
        s       = json_sizes[key_str]
        min_sep = s.get('min_sep')          # None or float
        prob    = s.get('probability', 0.01)
    else:
        fallback = SIZE_PARAMS_FALLBACK.get((wt, ht))
        if fallback:
            min_sep, prob = fallback
        else:
            min_sep = round(max(wt, ht) * 1.8, 1)
            prob    = 0.01

    return hw, hh, min_sep, prob


groups = defaultdict(list)
for d in data['decals']:
    groups[(d['w_tiles'], d['h_tiles'])].append(d)

lines = [
    '-- Generated by scripts/generate_decal_lua.py — do not edit manually.',
    '',
    f'local ATLAS = "{ATLAS}"',
    '',
    'data:extend({',
]

bound_names = []
for (wt, ht), entries in sorted(groups.items(), key=lambda kv: -(kv[0][0]*kv[0][1])):
    hw, hh, min_sep, prob = get_params(wt, ht)
    name  = f'heliara_wsc_decal_{wt}x{ht}'
    order = f'b[decal]-d[heliara-wsc]-s[{wt:02d}x{ht:02d}]'
    bound_names.append(name)

    block = [
        '  {',
        f'    type           = "optimized-decorative",',
        f'    name           = "{name}",',
        f'    order          = "{order}",',
        f'    collision_box  = {{{{-{hw}, -{hh}}}, {{{hw}, {hh}}}}},',
        f'    collision_mask = {{layers = {{water_tile = true}}, colliding_with_tiles_only = true}},',
        f'    render_layer   = "decals",',
        f'    tile_layer     = 255,',
    ]
    if min_sep is not None:
        block.append(f'    minimal_separation = {min_sep},')
    block += [
        f'    autoplace = {{',
        f'      order                  = "{order}",',
        f'      probability_expression = "{prob}",',
        f'      tile_restriction       = {{ "heliara_weathered_siliceous_crust" }},',
        f'    }},',
        '    pictures = {',
    ]
    lines += block
    for e in entries:
        lines.append(
            f'      {{ filename = ATLAS, x = {e["x"]:5d}, y = {e["y"]:5d},'
            f' width = {e["width"]}, height = {e["height"]}, scale = 0.5, shift = {{0, 0}} }},'
        )
    lines += ['    },', '  },', '']

lines.append('})')
lines.append('')

LUA_OUT.write_text('\n'.join(lines))
print(f'Wrote {LUA_OUT}')
print(f'bound_decoratives = {{ {", ".join(repr(n) for n in bound_names)} }}')
